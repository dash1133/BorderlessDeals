step = float(sys.argv[1]) if len(sys.argv) > 1 else 8
dots = []
y = step/2
while y < H:
    x = step/2
    while x < W:
        if any(inside(x, y, p) for p in polys): dots.append((round(x,1), round(y,1)))
        x += step
    y += step
r = step*0.3
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">']
svg += [f'<circle cx="{x}" cy="{y}" r="{r:.2f}" fill="#B9C6E4"/>' for x, y in dots]
svg.append('</svg>')
